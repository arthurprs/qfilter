/// Old implementation: loop-based bit clearing
#[inline]
fn select_loop(x: u64, n: u64) -> Option<u64> {
    let mut v = x;
    for _ in 0..n / 8 {
        for _ in 0..8 {
            v &= v.wrapping_sub(1);
        }
    }
    for _ in 0..n % 8 {
        v &= v.wrapping_sub(1);
    }
    if v == 0 {
        None
    } else {
        Some(v.trailing_zeros() as u64)
    }
}

const L8: u64 = 0x0101_0101_0101_0101;

#[inline(always)]
fn le8(x: u64, y: u64) -> u64 {
    ((y | 0x8080_8080_8080_8080).wrapping_sub(x & !0x8080_8080_8080_8080)) & 0x8080_8080_8080_8080
}

#[inline(always)]
fn u_nz8(x: u64) -> u64 {
    ((x | 0x8080_8080_8080_8080).wrapping_sub(L8) | x) & 0x8080_8080_8080_8080
}

/// Current implementation: Vigna's pure broadword select
#[inline]
fn select_broadword(x: u64, n: u64) -> Option<u64> {
    let mut s = x - ((x & 0xAAAA_AAAA_AAAA_AAAA) >> 1);
    s = (s & 0x3333_3333_3333_3333) + ((s >> 2) & 0x3333_3333_3333_3333);
    s = ((s + (s >> 4)) & 0x0F0F_0F0F_0F0F_0F0F).wrapping_mul(L8);

    let b = (le8(s, n.wrapping_mul(L8)) >> 7).wrapping_mul(L8) >> 53 & !7;
    let l = n - ((s << 8).wrapping_shr(b as u32) & 0xFF);

    s = (u_nz8((x.wrapping_shr(b as u32) & 0xFF).wrapping_mul(L8) & 0x8040_2010_0804_0201) >> 7)
        .wrapping_mul(L8);

    let result = b + ((le8(s, l.wrapping_mul(L8)) >> 7).wrapping_mul(L8) >> 56);
    if result == 72 {
        None
    } else {
        Some(result)
    }
}

/// Table with byte_rank/bit_pos bounds checks (no upfront popcount)
#[inline]
fn select_table(x: u64, n: u64) -> Option<u64> {
    const ONES_STEP_4: u64 = 0x1111_1111_1111_1111;
    const ONES_STEP_8: u64 = 0x0101_0101_0101_0101;
    const LAMBDAS_STEP_8: u64 = 0x80 * ONES_STEP_8;

    let mut s = x;
    s = s - ((s & (0xA * ONES_STEP_4)) >> 1);
    s = (s & (0x3 * ONES_STEP_4)) + ((s >> 2) & (0x3 * ONES_STEP_4));
    s = (s + (s >> 4)) & (0xF * ONES_STEP_8);
    let byte_sums: u64 = s.wrapping_mul(ONES_STEP_8);

    let rank_step_8: u64 = n.wrapping_mul(ONES_STEP_8);
    let geq_rank_step_8: u64 =
        ((rank_step_8 | LAMBDAS_STEP_8).wrapping_sub(byte_sums)) & LAMBDAS_STEP_8;
    let place = geq_rank_step_8.count_ones() * 8;
    let byte_rank: u64 = n.wrapping_sub(((byte_sums << 8).wrapping_shr(place)) & 0xFF);
    if byte_rank >= 8 {
        return None;
    }
    let index = (x.wrapping_shr(place) & 0xFF) | (byte_rank << 8);
    let bit_pos = SELECT_IN_BYTE[index as usize];
    if bit_pos >= 8 {
        return None;
    }
    Some(place as u64 + bit_pos as u64)
}

