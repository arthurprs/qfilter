//! Portable bit selection algorithm.
//!
//! Uses broadword prefix sums to locate the target byte, then a 2048-entry
//! lookup table to select within that byte. Based on Vigna's broadword
//! select algorithm with the table-based final step from his common_traits
//! crate (Apache-2.0).

#![cfg_attr(
    all(
        target_arch = "x86_64",
        not(feature = "legacy_x86_64_support"),
        not(target_feature = "bmi2")
    ),
    allow(dead_code)
)]

/// Select the position of the n-th set bit (0-indexed) in `x`.
///
/// Returns `None` if there are fewer than `n + 1` set bits.
#[inline]
pub fn select(x: u64, n: u64) -> Option<u64> {
    const ONES_STEP_4: u64 = 0x1111_1111_1111_1111;
    const ONES_STEP_8: u64 = 0x0101_0101_0101_0101;
    const LAMBDAS_STEP_8: u64 = 0x80 * ONES_STEP_8;

    // Parallel popcount per byte, then prefix sum
    let mut s = x;
    s = s - ((s & (0xA * ONES_STEP_4)) >> 1);
    s = (s & (0x3 * ONES_STEP_4)) + ((s >> 2) & (0x3 * ONES_STEP_4));
    s = (s + (s >> 4)) & (0xF * ONES_STEP_8);
    let byte_sums: u64 = s.wrapping_mul(ONES_STEP_8);

    // Find which byte contains the n-th bit using popcount
    let rank_step_8: u64 = n.wrapping_mul(ONES_STEP_8);
    let geq_rank_step_8: u64 =
        ((rank_step_8 | LAMBDAS_STEP_8).wrapping_sub(byte_sums)) & LAMBDAS_STEP_8;
    let place = geq_rank_step_8.count_ones() * 8;

    // Rank within that byte — if >= 8, the n-th bit doesn't exist
    let byte_rank: u64 = n.wrapping_sub(((byte_sums << 8).wrapping_shr(place)) & 0xFF);
    if byte_rank >= 8 {
        return None;
    }
    let index = (x.wrapping_shr(place) & 0xFF) | (byte_rank << 8);
    // SELECT_IN_BYTE returns 8 when the rank-th bit doesn't exist in the byte
    let bit_pos = SELECT_IN_BYTE[index as usize];
    if bit_pos >= 8 {
        return None;
    }
    Some(place as u64 + bit_pos as u64)
}

